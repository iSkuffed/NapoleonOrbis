def append_composites(sp, pinfo, major):
    pg = next(cm._iter_recs(sp.root, 'PATHFINDING_GRID')).items[0]
    b8 = bytearray(pg[8].value)
    f11 = list(struct.unpack(f'<{len(b8)}f', pg[11].value))
    dk = {**pinfo['domains'], **pinfo.get('vanilla_domains', {})}     # world_regions stage 'j': vanilla members too
    for name, d in sorted(pinfo['composites'].items(), key=lambda kv: kv[1]):
        assert d == len(b8), (name, d, len(b8))
        b8.append(int(all(b8[dk[k]] for k in name.split('+'))))
