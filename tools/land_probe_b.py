def land_trade_routes(info, place, first):
    """(a, b, length) per pair of new settlements whose regions share a border: vanilla has a trade route for every
    pair of adjacent settled regions (137 of 137, 37 of them spline-less like these), and the turn-start trade route
    pass (0xB83C30, pair map at +0x1A0 keyed (min, max) settlement node) reads the found node without a NULL check, so
    two factions bordering here without one crash it (b3 turn 2, key (112, 113))."""
    out = []
    for (n, a), (m, b) in itertools.combinations(enumerate(KEYS), 2):
        if info['polys'][a].boundary.intersection(info['polys'][b].boundary).length > 0:
            ln = math.dist(place[a]['pos'], place[b]['pos'])
            out.append((first + n, first + m, struct.unpack('<f', struct.pack('<f', ln))[0]))
    return out


