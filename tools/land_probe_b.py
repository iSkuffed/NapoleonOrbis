def features():
    """{key: world polygon} for every 1805 feature near the three regions (holes filled, parts unioned, simplified)."""
    g = json.load(open(GEOJSON))
    shp = {f['properties']['key']: shape(f['geometry']) for f in g['features']}
    mine = shapely.union_all([shp[k] for k in KEYS])
    x0, y0, x1, y1 = mine.bounds
    near = box(x0 - 4, y0 - 4, x1 + 4, y1 + 4)
    out = {}
    for k, s in shp.items():
        if not s.intersects(near):
            continue
        parts = [lonlat_poly(list(p.exterior.coords)) for p in getattr(s, 'geoms', [s])]
        out[k] = shapely.make_valid(shapely.simplify(shapely.union_all(parts), SIMPLIFY))
    # seaward skirt: each polygon grows by SKIRT where no other polygon is, overlaps go to the earlier key, so the cut
    # lines meet the filler coast only where two polygons meet near it (no coast-mismatch slivers)
    allf = shapely.union_all(list(out.values()))
    grown, taken = {}, None
    for k in sorted(out, key=lambda k: (k in KEYS, k)):
        g = shapely.union_all([out[k], out[k].buffer(SKIRT).difference(allf)])
        if taken is not None:
            g = g.difference(taken)
        grown[k] = shapely.union_all([Polygon(q.exterior) for q in shapely.get_parts(shapely.make_valid(g))
                                      if q.geom_type == 'Polygon'])
        taken = grown[k] if taken is None else shapely.union_all([taken, grown[k]])
    return grown


def ring_edges(coords):
    return list(zip(coords, coords[1:] + coords[:1]))


def merge_faces(rings):
    """Directed-edge union of CCW faces (tuples of points) -> [ring]; edges shared by two faces cancel. Returns None if
    the boundary pinches (a vertex with two outgoing edges)."""
    E = collections.Counter()
    for r in rings:
        for a, b in ring_edges(r):
            E[(a, b)] += 1
    out = {}
    for (a, b) in E:
        if (b, a) in E:
            continue
        if a in out:
            return None
        out[a] = b
    res = []
    while out:
        a = next(iter(out))
        r = [a]
        b = out.pop(a)
        while b != r[0]:
            r.append(b)
            b = out.pop(b)
        res.append(r)
    return res


def signed_area(r):
    x = np.array([p[0] for p in r]); y = np.array([p[1] for p in r])
    return 0.5 * float((x * np.roll(y, -1) - np.roll(x, -1) * y).sum())


def partition_filler(A, feats):
    """Faces of A cut by the 1805 feature borders -> {label: [rings (point tuples)]}, label = region key or None
    (= stays filler). Faces outside every feature (coast mismatch) and stray pieces join the neighbour label they share
    the longest border with, so each region is one ring and the filler keeps one outer ring."""
    cut = shapely.set_precision(MultiLineString([r for f in feats.values() for p in getattr(f, 'geoms', [f])
                                                 for r in [p.exterior] + list(p.interiors)]), GRID)
    net = shapely.union_all([A.exterior, cut])           # exact noding: the filler's own vertices are not all on GRID
    faces = [p for p in shapely.get_parts(shapely.polygonize(shapely.get_parts(net))) if A.contains(p.representative_point())]
    assert abs(sum(p.area for p in faces) - A.area) < 1e-6 * A.area, 'faces must tile the filler area'
    rings, lab = [], []
    tree_keys = list(feats)
    for p in faces:
        o = shapely.geometry.polygon.orient(p, 1.0)       # outer CCW, holes CW: edges of all rings cancel pairwise
        rings.append([tuple((float(x), float(y)) for x, y in r.coords[:-1]) for r in [o.exterior] + list(o.interiors)])
        q = p.representative_point()
        hit = [k for k in tree_keys if feats[k].contains(q)]
        lab.append(hit[0] if hit else None if p.area > BIG_GAP else '?')
        if lab[-1] not in KEYS and lab[-1] != '?':
            lab[-1] = None
    # face adjacency with shared length
    owner = {}
    for i, rs in enumerate(rings):
        for r in rs:
            for e in ring_edges(r):
                owner[e] = i
    adj = collections.defaultdict(collections.Counter)
    for (a, b), i in owner.items():
        j = owner.get((b, a))
        if j is not None and j != i:
            adj[i][j] += math.dist(a, b)

    def components(label):
        idx = [i for i, l in enumerate(lab) if l == label]
        seen, comps = set(), []
        for i in idx:
            if i in seen:
                continue
            comp, todo = [], [i]
            seen.add(i)
            while todo:
                k = todo.pop(); comp.append(k)
                for j in adj[k]:
                    if j not in seen and lab[j] == label:
                        seen.add(j); todo.append(j)
            comps.append(comp)
        return comps

    keep = {r['key']: Point(*map(float, proj.to_world(*r['keep_at']))) for r in REGIONS if 'keep_at' in r}
    for _ in range(50):
        changed = 0
        for i, l in enumerate(lab):                       # unassigned faces: longest assigned neighbour
            if l == '?':
                c = collections.Counter()
                for j, ln in adj[i].items():
                    if lab[j] != '?':
                        c[lab[j]] += ln
                if c:
                    lab[i] = c.most_common(1)[0][0]; changed += 1
        for label in KEYS + [None]:                       # keep the largest component of each label (or keep_at's)
            comps = components(label)
            comps.sort(key=lambda cc: (label in keep and not any(faces[k].contains(keep[label]) for k in cc),
                                       -sum(faces[k].area for k in cc)))
            for cc in comps[1:]:
                c = collections.Counter()
                for k in cc:
                    for j, ln in adj[k].items():
                        if j not in cc:
                            c[lab[j]] += ln
                if c:
                    new = c.most_common(1)[0][0]
                    for k in cc:
                        lab[k] = new
                    changed += 1
        if not changed:
            break
    assert '?' not in lab
    out = {}
    for label in KEYS + [None]:
        rs = merge_faces([r for i, l in enumerate(lab) if l == label for r in rings[i]])
        assert rs is not None, ('pinched boundary', label)
        outer = [r for r in rs if signed_area(r) > 0]
        assert len(outer) == 1 and (label is None or len(rs) == 1), (label, len(outer), len(rs))
        out[label] = rs
    return out


def carve(e):
    """Cut the three regions out of the eur_map_west area at INSIDE_PT -> info. Region items cloned from TPL (settlement
    set later by place_settlements), areas: passable, one shared new pass_group, the filler's landmass."""
    rd = e.root.find('region_data')
    items = rd.find('regions').items
    names = [it[0].value for it in items]
    wi = names.index('eur_map_west')
    polys = rm.area_polygons(rd)
    p = Point(*map(float, proj.to_world(*INSIDE_PT)))
    code = next(c for c, q in polys.items() if c >> 16 == wi and q.contains(p))
    ai = code & 0xFFFF
    ar61 = rm.sub(items[wi], 'areas').items[ai]
    f61 = rm.area_fields(ar61)
    assert not f61['passable'] and len(rm.rings(ar61)) == 1
    A = polys[code]
    V = rm.verts(rd)
    pool = {(float(x), float(y)): i for i, (x, y) in enumerate(V)}
    assert len(pool) == len(V)
    old_ring = rm.rings(ar61)[0][1].tolist()
    parts = partition_filler(A, features())
    newV = []

    def idx(pt):
        i = pool.get(pt)
        if i is None:                                    # new node: rounded to GRID (exact in float32)
            q = (round(pt[0] / GRID) * GRID, round(pt[1] / GRID) * GRID)
            i = pool.get(q)
            if i is None:
                i = pool[q] = len(V) + len(newV); newV.append(q)
        return i

    def dedup(r):
        r = [idx(q) for q in r]
        return [v for k, v in enumerate(r) if v != r[k - 1]]
    rings = {k: [(signed_area(r) > 0, dedup(r)) for r in rs] for k, rs in parts.items()}
    # every old filler vertex survives; old boundary edges split by new vertices -> same chain in the twin (sea) ring
    used = {i for rs in rings.values() for _, r in rs for i in r}
    assert set(old_ring) <= used, 'filler vertex lost'
    E = {(a, b) for rs in rings.values() for _, r in rs for a, b in zip(r, r[1:] + r[:1])}
    bnd = {a: b for a, b in E if (b, a) not in E}
    split = {}
    for a, b in zip(old_ring, old_ring[1:] + old_ring[:1]):
        if bnd.get(a) == b:
            continue
        chain, v = [], bnd[a]
        while v != b:
            chain.append(v); v = bnd[v]
            assert len(chain) < 1000
        split[(a, b)] = chain
    own = rm.edge_owner(rd)
    nsplit = 0
    for (a, b), chain in split.items():
        c = own[(b, a)]
        tar = rm.sub(items[c >> 16], 'areas').items[c & 0xFFFF]
        for _, rr, ol in rm.rings(tar):
            r = rr.tolist()
            for k in range(len(r)):
                if r[k] == b and r[(k + 1) % len(r)] == a:
                    r[k + 1:k + 1] = chain[::-1]
                    ol[3] = rm.mkarr(0x48, np.array(r, np.uint32)); nsplit += 1
                    break
    assert nsplit == len(split)
    rd.find('vertices').children[0] = rm.mkarr(0x4c, np.vstack([V, np.array(newV, np.float32).reshape(-1, 2)]))
    V2 = rm.verts(rd)
    tmpl_outline = rm.sub(ar61, 'outlines').items[0]
    set_rings(ar61, rings[None], tmpl_outline)
    rm.sub(ar61, 'faces').children[0] = rm.mkarr(0x48, rm.triangulate(V2, [[(o, np.array(r)) for o, r in rings[None]]]).ravel())
    allpg = [rm.area_fields(a)['pass_group'] for _, _, _, a in rm.iter_areas(rd)]
    pass_group = max(allpg) + 1
    tpl = items[names.index(TPL)]
    first = len(items)
    for k in KEYS:
        ar = clone(ar61)
        ar[2], ar[5], ar[8] = Val(0x01, True), Val(0x07, pass_group), Val(0x07, 0xFFFF)
        set_rings(ar, rings[k], tmpl_outline)
        rm.sub(ar, 'faces').children[0] = rm.mkarr(0x48, rm.triangulate(V2, [[(o, np.array(r)) for o, r in rings[k]]]).ravel())
        it = clone(tpl)
        it[0] = Val(0x0e, k)
        rm.sub(it, 'areas').items = [ar]
        items.append(it)
    rm.rebuild_bounds(rd)
    rd.children[1], rd.children[2] = Val(0x0c, tuple(map(float, proj.BOX_MIN))), Val(0x0c, tuple(map(float, proj.BOX_MAX)))
    rm.rebuild_connectivity(rd)
    P = rm.area_polygons(rd)
    return dict(filler_area=ai, filler_fields={k: v for k, v in f61.items() if k not in ('bmin', 'bmax')},
                pass_group=pass_group, first_index=first, new_vertices=len(newV), split_sea_edges=nsplit,
                polys={k: P[(first + n) << 16] for n, k in enumerate(KEYS)}, filler_poly=P[code])


def place_slots(it, key, town, pos, D):
    """TPL settlement + KEEP_SLOTS of region item `it` moved by D, renamed to key/town (= land_probe.regions_finish)."""
    ss = rm.sub(it, 'settlement_and_slots')
    ss.children[0] = Val(0x0c, pos)
    shift = lambda v: rm.mkarr(0x4c, rm.nparr(v) + np.array(D, np.float32)) if v.value else v
    ss.children[1] = shift(ss.children[1])
    sd = ss.find('slot_descriptions')
    keep = [s for s in sd.items if s[1].value in lp.KEEP_SLOTS]
    assert len(keep) == 3
    for k, s in enumerate(keep):
        typ, suf = s[1].value, int(s[0].value.rsplit(':', 1)[1])
        assert suf == k, s[0].value
        s[0] = Val(0x0e, f'settlement:{key}:{town}:{typ}:{k}')
        x, h, y = s[2].value
        s[2] = Val(0x0d, (lp.f32(x + D[0]), h, lp.f32(y + D[1])))
        s[3] = Val(0x0c, (lp.f32(s[3].value[0] + D[0]), lp.f32(s[3].value[1] + D[1])))
        for j in (7, 8, 9):
            s[j] = shift(s[j])
    sd.items = keep


def slot_geometry(it, land=False, skip=()):
    """[shapely geometry] of the settlement point, footprint and slot geometry of region item `it`. land: a port slot
    gives only its building and land half (the dock and sea half lie on the sea; port_probe.check covers those).
    skip: slot keys giving only their building point."""
    ss = rm.sub(it, 'settlement_and_slots')
    out = [Point(ss.children[0].value)]
    if ss.children[1].value:
        out.append(Polygon(rm.nparr(ss.children[1])))
    for s in ss.find('slot_descriptions').items:
        if s[0].value in skip:
            out.append(Point(s[2].value[0], s[2].value[2]))
            continue
        if land and s[0].value.startswith('port:'):
            out += [Point(s[2].value[0], s[2].value[2]), shapely.MultiPoint(rm.nparr(s[7]))]
            continue
        out.append(Point(s[3].value))
        out += [shapely.MultiPoint(rm.nparr(s[j])) for j in (7, 9) if s[j].value]
    return out


# ---------------------------------------------------------------- pathfinding.esf
def band_polygon(poly_w):
    """Region polygon grown by BAND, fixed units, snapped like the land ring (explicit grid-line crossings)."""
    b = shapely.simplify(shapely.transform(poly_w, lambda c: c * FIX).buffer(BAND * FIX), 0.02 * FIX)
    assert b.geom_type == 'Polygon'                       # holes = water the band closes over (bays), kept
    q = Polygon(lp.snap_ring(list(b.exterior.coords)), [lp.snap_ring(list(h.coords)) for h in b.interiors])
    assert q.is_valid
    return q


def pathfinding(path, polys, first):
    """-> (model, info). Off-map polygons inside the three regions become land Ls = (off-map ∩ ∪regions) shrunk by
    LAND_BAND (no shrink along the shared borders); a land point's path domain is the set of regions whose BAND-grown
    polygon covers it: one region = its singleton domain, 2-3 = a composite domain (vanilla recipe)."""
    m = pm.PathfindingModel.load(path)
    area = m.areas[0]
    g, P = area.grid, area.polygons()
    C, R = g.columns, g.rows
    doms = [lp.renumber_domains(g, first + n) for n in range(len(KEYS))]
    sea = lp.sea_id(g)
    Uf = [shapely.transform(polys[k], lambda c: c * FIX) for k in KEYS]
    U = shapely.union_all(Uf)
    ox, oy = g.origin_fixed
    x0, y0, x1, y1 = U.bounds
    cols = range(int((x0 - ox) // S) - 2, int((x1 - ox) // S) + 3)
    rows = range(int((y0 - oy) // S) - 2, int((y1 - oy) // S) + 3)
    assert cols[0] >= 0 and rows[0] >= 0 and cols[-1] < C and rows[-1] < R
    cand = [r * C + c for r in rows for c in cols]
    cp = {k: probe_g3.cell_polys(area, P, k) for k in cand}
    offp = {k: [j for j, (t, q) in enumerate(cp[k]) if t == lp.OFF] for k in cand}
    O = shapely.union_all([Polygon(cp[k][j][1]) for k in cand for j in offp[k]])
    L = O.intersection(U).buffer(-LAND_BAND * FIX)
    parts = sorted(shapely.get_parts(L), key=lambda p: -p.area)
    L = shapely.simplify(parts[0], 0.05 * FIX)
    L = max(shapely.get_parts(L), key=lambda p: p.area)
    assert not L.interiors
    ring = lp.snap_ring(list(L.exterior.coords))
    Ls = Polygon(ring)
    assert Ls.is_valid and all(lp.edge_in_cell(p, q) for p, q in zip(ring, ring[1:] + ring[:1]))
    assert Ls.within(O) and O.boundary.distance(Ls) > 0.5 * LAND_BAND * FIX
    B = [band_polygon(polys[k]) for k in KEYS]
    blines = [shapely.intersection(b.exterior, Ls) for b in B]     # inside the land only: never moves an off-map edge
    # composite domains: every 2-3 region set whose bands overlap on the land, appended to the path table
    comps = []
    for n in (2, 3):
        for T in itertools.combinations(range(len(KEYS)), n):
            z = shapely.intersection_all([Ls] + [B[i] for i in T])
            if z.area > 0:
                comps.append(T)
    pos1 = {ri: n + 1 for n, ri in enumerate(g.region_indices)}       # path table refs are 1-based
    base = len(g.path_domains())
    for T in comps:
        g.path_table = g.path_table + (len(T),) + tuple(pos1[first + i] for i in T)
    dom_of = {(n,): doms[n] for n in range(len(KEYS))}
    dom_of.update({T: base + n for n, T in enumerate(comps)})
    mine = set(dom_of.values())
    assert [g.path_domains()[dom_of[T]] for T in comps] == [tuple(first + i for i in T) for T in comps]

    def label(q):
        T = tuple(n for n, b in enumerate(B) if b.covers(q))
        assert T in dom_of, ('land point in no domain', T, q)
        return T

    verts = list(area.vertices_fixed)
    vid = {}
    for n, p in enumerate(verts):
        if n >= 4:
            vid.setdefault(p, n)
    key = max(P) + 1000
    kept = bytearray(b'\x01' * (C * R))
    stats = collections.Counter()

    def ids_of(k, p):
        p = shapely.simplify(p, 0)
        pts = [(int(a), int(b)) for a, b in p.exterior.coords[:-1]]
        assert all(float(a) == q[0] and float(b) == q[1] for (a, b), q in zip(p.exterior.coords[:-1], pts))
        if not p.exterior.is_ccw:
            pts.reverse()
        corners = g.corners(k)
        out = []
        for q in pts:
            if q in corners:
                out.append(corners.index(q))
            else:
                if q not in vid:
                    vid[q] = len(verts); verts.append(q)
                out.append(vid[q])
        return tuple(out)

    def merged(faces):
        u = shapely.union_all(faces, grid_size=1.0)
        ps = [p for p in shapely.get_parts(u) if p.area > 0]
        if any(p.interiors for p in ps):                  # a merge closed a ring: keep the faces apart
            stats['unmerged (hole)'] += 1
            ps = faces
        assert not any(p.interiors for p in ps)
        return sorted(ps, key=lambda p: -p.area)

    for k in cand:
        cellbox = box(*g.corners(k)[0], *g.corners(k)[3])
        if not offp[k] or not cellbox.intersects(Ls) or shapely.intersection(cellbox, Ls).area == 0:
            continue
        kept[k] = 0
        c = g.cells[k]
        Of = shapely.union_all([Polygon(cp[k][j][1]) for j in offp[k]], grid_size=1.0)
        lines = [cellbox.boundary, shapely.intersection(Ls.exterior, cellbox)]
        lines += [shapely.intersection(bl, cellbox) for bl in blines]
        lines += [Polygon(cp[k][j][1]).exterior for j in offp[k]]
        net = shapely.union_all([x for x in lines if not x.is_empty], grid_size=1.0)
        land, off = collections.defaultdict(list), []
        for f in shapely.get_parts(shapely.polygonize(shapely.get_parts(net))):
            q = f.representative_point()
            if not Of.covers(q):
                continue
            (land[label(q)] if Ls.covers(q) else off).append(f)
        tot = sum(f.area for fs in land.values() for f in fs) + sum(f.area for f in off)
        assert abs(tot - Of.area) < 1.0, ('faces must tile the off-map of the cell', k, tot, Of.area)
        if len(land) == 1 and not off and abs(Of.area - S * S) < 1.0:
            T = next(iter(land))
            g.cells[k] = pm.Cell(c.costs8, uniform=pm.Trait(0, 0, 255, dom_of[T])); stats['uniform land'] += 1
            continue
        bounds = [b for j, b in enumerate(c.boundaries) if j not in offp[k]]
        pieces = [[T, p] for T in sorted(land, key=lambda T: (len(T), T)) for p in merged(land[T])]
        while len(pieces) > MAX_LAND_POLYS:               # middle20 links only a neighbour's first 4 land polygons
            sm = min(pieces, key=lambda tp: tp[1].area)
            o = max((tp for tp in pieces if tp is not sm), key=lambda tp: sm[1].boundary.intersection(tp[1].boundary).length)
            u = shapely.union_all([sm[1], o[1]], grid_size=1.0)
            assert u.geom_type == 'Polygon' and not u.interiors, ('cannot merge a small land piece', k)
            o[1] = u; pieces.remove(sm)
            stats['small land pieces relabelled (>4 per cell)'] += 1
        nl = 0
        for T, p in pieces:
            P[key] = ids_of(k, p); bounds.append(pm.Boundary(pm.Trait(0, 0, 255, dom_of[T]), key)); key += 1; nl += 1
        for p in merged(off) if off else []:
            P[key] = ids_of(k, p); bounds.append(pm.Boundary(lp.OFF, key)); key += 1
        g.cells[k] = pm.Cell(c.costs8, bounds)
        stats['mixed'] += 1
        stats['max land polys/cell'] = max(stats['max land polys/cell'], nl)
        stats['cells >4 land polys'] += nl > 4
        stats['cells with 2+ domains'] += len(land) > 1
    area.vertices_fixed = tuple(verts)
    pf_gen.weld(area, P, kept)
    mod = [k for k in range(C * R) if not kept[k]]
    isl = lambda t: t.kind == 0 and t.path_id in mine
    for k in mod:
        for b in g.cells[k].boundaries:
            if isl(b.trait):
                b.trait = pm.Trait(0, 0, pm.contact_mask(area.points(k, P[b.polygon_offset]), g.corners(k)), b.trait.path_id)
    for k in mod:
        c = g.cells[k]
        if c.uniform is not None:
            t = c.uniform
            g.cells[k] = pm.Cell(c.costs8, uniform=pm.Trait(0, probe_g3.middle20(area, P, k, area.points(k, (0, 2, 3, 1)), t),
                                                            255, t.path_id))
            continue
        for b in c.boundaries:
            if isl(b.trait):
                t = b.trait
                b.trait = pm.Trait(0, probe_g3.middle20(area, P, k, area.points(k, P[b.polygon_offset]), t), t.contact_mask, t.path_id)
    for k in mod:
        r, col = divmod(k, C)
        cs = bytearray(g.cells[k].costs8)
        mk = land_mask(g.cells[k], mine)
        for d, (dx, dy) in enumerate(lp.DIRS):
            j = (r + dy) * C + col + dx
            if mk >> d & 1 and land_mask(g.cells[j], mine) >> lp.OPP[d] & 1:
                cs[d] = lp.LAND_COST
            elif cs[d] in (0x1f, 0xff, 1):
                cs[d] = lp.BLOCKED
        c = g.cells[k]
        g.cells[k] = pm.Cell(bytes(cs), c.boundaries, c.uniform)
    pf_gen.compact(area, P)
    stats['modified cells'] = len(mod)
    stats['land parts dropped (u^2)'] = round(sum(p.area for p in parts[1:]) / FIX / FIX, 1)
    to_w = lambda p: shapely.transform(p, lambda c: c / FIX)
    single = {KEYS[n]: to_w(Ls.intersection(B[n]).difference(shapely.union_all([B[i] for i in range(len(KEYS)) if i != n])))
              for n in range(len(KEYS))}
    info = dict(domains={KEYS[n]: doms[n] for n in range(len(KEYS))}, sea=sea,
                composites={'+'.join(KEYS[i] for i in T): dom_of[T] for T in comps},
                composite_area_u2={'+'.join(KEYS[i] for i in T): round(shapely.intersection_all([Ls] + [B[i] for i in T]).area / FIX / FIX, 2)
                                   for T in comps},
                stats=dict(stats), land_u2=round(Ls.area / FIX / FIX, 1))
    return m, to_w(Ls), single, info


def land_mask(c, doms):
    if c.uniform is not None:
        return 255 if c.uniform.kind == 0 and c.uniform.path_id in doms else 0
    m = 0
    for b in c.boundaries:
        if b.trait.kind == 0 and b.trait.path_id in doms:
            m |= b.trait.contact_mask
    return m


def place_settlements(e, info, single):
    """Per region: template offset D (multiples of 10 u, LOS blocks move whole) whose settlement lies in the region's
    singleton land with >= 3 u margin and whose footprint + slots lie inside the region polygon and the exe's
    building-display box (not for the us trio, which needs the patched exe), closest to the 1805 capital / anchor."""
    rd = e.root.find('region_data')
    items = rd.find('regions').items
    names = [it[0].value for it in items]
    tpl = items[names.index(TPL)]
    tpos = rm.sub(tpl, 'settlement_and_slots').children[0].value
    caps = {f['properties']['key']: f['properties'] for f in json.load(open(GEOJSON))['features']}
    boxed = TRIO != 'us'
    out = {}
    for n, r in enumerate(REGIONS):
        k = r['key']
        Z, Rp = single[k], info['polys'][k]
        cap = Point(*map(float, proj.to_world(*r.get('anchor', (caps[k]['capital']['lon'], caps[k]['capital']['lat'])))))
        x0, y0, x1, y1 = Z.bounds
        best = None
        for dx in range(math.floor((x0 - tpos[0]) / 10) * 10, math.ceil((x1 - tpos[0]) / 10) * 10 + 1, 10):
            for dy in range(math.floor((y0 - tpos[1]) / 10) * 10, math.ceil((y1 - tpos[1]) / 10) * 10 + 1, 10):
                p = Point(tpos[0] + dx, tpos[1] + dy)
                if not (Z.contains(p) and Z.boundary.distance(p) > 3.0):
                    continue
                it = clone(tpl)
                place_slots(it, k, r['town'], (lp.f32(p.x), lp.f32(p.y)), (float(dx), float(dy)))
                sg = slot_geometry(it)
                if all(Rp.contains(q) for q in sg) and (not boxed or in_display_box(sg)) and (best is None or p.distance(cap) < best[0]):
                    best = (p.distance(cap), (float(dx), float(dy)))
        assert best, ('no settlement spot', k)
        D = best[1]
        out[k] = dict(D=D, pos=(lp.f32(tpos[0] + D[0]), lp.f32(tpos[1] + D[1])), capital_distance_u=round(best[0], 1))
    return out


