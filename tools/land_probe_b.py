def land_graph(area, P, mine):
    """Land polygons of the domains `mine` -> (nodes {(cell, j): (trait, pts)}, adjacency with the link kind). Links:
    same-cell polygons sharing an edge; 4-neighbour cells whose polygons share a side segment and whose costs8 open
    the step both ways. Also counts geometric side links whose middle20 bit is missing."""
    g = area.grid
    C = g.columns
    nodes = {}
    for k, c in enumerate(g.cells):
        for j, (t, q) in enumerate(probe_g3.cell_polys(area, P, k)):
            if t.kind == 0 and t.path_id in mine:
                nodes[(k, j)] = (t, q)
    adj = collections.defaultdict(set)
    miss = 0
    nib = {0: (0, -1, 1, 0), 1: (-1, 0, 0, 0), 3: (1, 0, 0, 1), 4: (0, 1, 1, 1)}
    step = {(1, 0): 0, (0, 1): 2, (0, -1): 5, (-1, 0): 7}
    for (k, j), (t, q) in nodes.items():
        r, col = divmod(k, C)
        (x0, y0), (x1, y1) = g.corners(k)[0], g.corners(k)[3]
        E = {frozenset(e) for e in zip(q, q[1:] + q[:1])}
        for j2, (t2, q2) in enumerate(probe_g3.cell_polys(area, P, k)):
            if j2 != j and (k, j2) in nodes and E & {frozenset(e) for e in zip(q2, q2[1:] + q2[:1])}:
                adj[(k, j)].add((k, j2))
        for n, (dx, dy, axis, hi) in nib.items():
            v = (x1, y1)[axis] if hi else (x0, y0)[axis]
            kn = (r + dy) * C + col + dx
            mine_s = probe_g3._on_line(q, axis, v)
            land_n = [(j2, q2) for j2, (t2, q2) in enumerate(probe_g3.cell_polys(area, P, kn))
                      if t2.kind not in (2, 3) and t2.path_id != lp.sea_id(g)]
            for idx, (j2, q2) in enumerate(land_n):
                if (kn, j2) not in nodes:
                    continue
                if any(min(a1, b1) > max(a0, b0) for a0, a1 in mine_s for b0, b1 in probe_g3._on_line(q2, axis, v)):
                    d = step[(dx, dy)]
                    if g.cells[k].costs8[d] == lp.LAND_COST and g.cells[kn].costs8[lp.OPP[d]] == lp.LAND_COST:
                        adj[(k, j)].add((kn, j2))
                    miss += not (idx < 4 and t.middle20 >> (4 * n + idx) & 1)
    return nodes, adj, miss


