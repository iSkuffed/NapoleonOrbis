def group_neighbours(sp, regions, adj, rid):
    """Every region group bordering one of regions (CAI ids) lists it as a neighbour (body[1], header j+19 = members +
    neighbours; the region's j+20 lists the group)."""
    import world_zones as wz
    ar = {(rid[a], rid[b]) for a, b in adj} | {(rid[b], rid[a]) for a, b in adj}
    n = 0
    comps = wz.cai_components(sp)
    by = {k[j + 1].value: (k, j) for k, j in comps}
    for k, j in comps:
        if isinstance(k[-1], Rec) and k[-1].name == 'CAI_BASIC_REGION_GROUP_ANALYSIS':
            gc = k[-1].children
            add = [r for r in regions if r not in gc[0].array() + gc[1].array() and any((x, r) in ar for x in gc[0].array())]
            if add:
                assert k[j + 19].array() == gc[0].array() + gc[1].array()
                gc[1] = wz.u32a(gc[1].array() + add)
                k[j + 19] = wz.u32a(gc[0].array() + gc[1].array())
                for r in add:
                    rk, rj = by[r]
                    rk[rj + 20] = wz.u32a(rk[rj + 20].array() + [k[j + 1].value])
                n += 1
    return n


